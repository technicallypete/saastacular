// plbDigest is a fixture SHA-256 digest (32 bytes).
func plbDigest(s string) []byte { b := sha256.Sum256([]byte("g057-catalog/" + s)); return b[:] }

// plbAttempt runs stmt under a savepoint of tx and returns its SQLSTATE ("" when it succeeded).
func plbAttempt(t *testing.T, tx pgx.Tx, stmt string, args ...any) string {
	t.Helper()
	ctx := context.Background()
	sp, err := tx.Begin(ctx)
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = sp.Rollback(ctx) }()
	_, err = sp.Exec(ctx, stmt, args...)
	return sqlstateOf(err)
}

// plbSetRole switches tx to role (SET LOCAL ROLE; the owner session may assume each helper, the attested superuser any).
func plbSetRole(t *testing.T, tx pgx.Tx, role string) {
	t.Helper()
	if _, err := tx.Exec(context.Background(), `SET LOCAL ROLE `+quote(role)); err != nil {
		t.Fatalf("SET LOCAL ROLE %s: %v", role, err)
	}
}

// plbProvision is the 8-argument provisioning call; every result column is rendered (NULL as the zero value).
const plbProvision = `SELECT outcome, coalesce(organization_id::text, ''), coalesce(slug, ''), coalesce(generation, 0),
  coalesce(target_origin, '') FROM app.signup_provision_organization($1, $2, $3, $4, $5, $6, $7, now())`

type plbOutcome struct {
	outcome, org, slug string
	generation         int
	target             string
}

func plbProvisionRow(t *testing.T, tx pgx.Tx, cred, name, slug string, label any, intent, ref, target string) plbOutcome {
	t.Helper()
	var o plbOutcome
	if err := tx.QueryRow(context.Background(), plbProvision, plbDigest(cred), name, slug, label, plbDigest(intent), plbDigest(ref), target).
		Scan(&o.outcome, &o.org, &o.slug, &o.generation, &o.target); err != nil {
		t.Fatalf("provision (%s, %v): %v", slug, label, err)
	}
	return o
}

